#!/usr/bin/env bash
# Generates gNB/UE ZMQ configs for each bandwidth profile (band n3, SCS 15 kHz).
# Profile: <bw_mhz> <srate_mhz> <nof_prb> <ssb_nr_arfcn> <coreset0_index>
# coreset0_index (TS 38.213 Table 13-1, 15/15 kHz): 12 = 96 RB @20 MHz (official srsUE tutorial),
# 6 = 48 RB @10/15 MHz (official multi-UE tutorial). 5 MHz is not offered: only CORESET#0 0-5
# (24 RB, 2-3 symbols) fit in 25 PRB and srsUE 25.10 never finds the cell with them (tested).
# ssb_nr_arfcn: value printed by the gNB as dl_ssb_arfcn (368410 for 10, 15 and 20 MHz, verified).
set -euo pipefail
LOG_LEVEL="${LOG_LEVEL:-warning}"   # gNB/UE file log level (info or debug for troubleshooting)
cd "$(dirname "$0")/../configs"
while read -r bw sr prb ssb cs0; do
cat > "gnb/gnb_zmq_${bw}mhz.yml" <<EOF
# srsRAN Project gNB (release_24_10_1) - ZMQ radio, band n3 FDD, ${bw} MHz, SCS 15 kHz.
# Generated by scripts/gen-radio-configs.sh from the official srsUE tutorial config.
cu_cp:
  amf:
    addr: 10.88.2.2                 # AMF NGAP address (ran network, N2)
    port: 38412
    bind_addr: 10.88.2.20           # gNB address on the ran network
    supported_tracking_areas:
      - tac: 7
        plmn_list:
          - plmn: "00101"
            tai_slice_support_list:
              - sst: 1
  inactivity_timer: 7200

cu_up:
  upf:
    bind_addr: 10.88.2.20           # N3 GTP-U local address

ru_sdr:
  device_driver: zmq
  device_args: tx_port=tcp://10.88.3.20:2000,rx_port=tcp://10.88.3.21:2001,base_srate=${sr}e6
  srate: ${sr}
  tx_gain: 75
  rx_gain: 75

cell_cfg:
  dl_arfcn: 368500                  # 1842.5 MHz
  band: 3
  channel_bandwidth_MHz: ${bw}
  common_scs: 15
  plmn: "00101"
  tac: 7
  pci: 1
  pdcch:
    common:
      ss0_index: 0                  # srsUE capability
      coreset0_index: ${cs0}             # srsUE capability
    dedicated:
      ss2_type: common
      dci_format_0_1_and_1_1: false
  prach:
    prach_config_index: 1
  pdsch:
    mcs_table: qam64
  pusch:
    mcs_table: qam64

log:
  filename: /logs/gnb.log
  all_level: ${LOG_LEVEL}
  hex_max_size: 0

pcap:
  mac_enable: true
  mac_filename: /captures/gnb_mac.pcap
  ngap_enable: true
  ngap_filename: /captures/gnb_ngap.pcap
EOF
cat > "ue/ue_zmq_${bw}mhz.conf" <<EOF
# srsUE (srsRAN 4G release_25_10) - 5G SA over ZMQ, band n3, ${bw} MHz (${prb} PRB).
# Generated by scripts/gen-radio-configs.sh from the official srsUE tutorial config.
[rf]
freq_offset = 0
tx_gain = 50
rx_gain = 40
srate = ${sr}e6
nof_antennas = 1
device_name = zmq
device_args = tx_port=tcp://10.88.3.21:2001,rx_port=tcp://10.88.3.20:2000,base_srate=${sr}e6

[rat.eutra]
dl_earfcn = 2850
nof_carriers = 0

[rat.nr]
bands = 3
nof_carriers = 1
dl_nr_arfcn = 368500
# must equal the dl_ssb_arfcn printed by the gNB for this bandwidth
ssb_nr_arfcn = ${ssb}
max_nof_prb = ${prb}
nof_prb = ${prb}

[pcap]
enable = mac_nr,nas
mac_nr_filename = /captures/ue_mac_nr.pcap
nas_filename = /captures/ue_nas.pcap

[log]
all_level = ${LOG_LEVEL}
phy_lib_level = none
all_hex_limit = 32
filename = /logs/ue.log
file_max_size = -1

[usim]
mode = soft
algo = milenage
opc  = 63BFA50EE6523365FF14C1F45F88737D
k    = 00112233445566778899aabbccddeeff
imsi = 001010123456780
imei = 353490069873319

[rrc]
release = 15
ue_category = 4

[nas]
apn = internet
apn_protocol = ipv4

[gw]
ip_devname = tun_srsue
ip_netmask = 255.255.0.0

[gui]
enable = false

[channel.dl]
enable = false

[channel.dl.awgn]
enable = false
snr = 30
EOF
done <<'PROFILES'
10 11.52 52 368410 6
15 15.36 79 368410 6
20 23.04 106 368410 12
PROFILES
echo "generated: $(ls gnb ue | tr '\n' ' ')"
